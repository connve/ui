// Writes src/lib/icons.ts: the Tabler icons the components show, as data for `@iconify/svelte`,
// so they render at once, offline too, without asking the Iconify API. To add one, put its
// Tabler name in NAMES and run `npm run icons`.

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const NAMES = [
	'check',
	'chevron-left',
	'chevron-right',
	'copy',
	'device-desktop',
	'folder',
	'folder-open',
	'git-pull-request',
	'layout-sidebar-left-collapse',
	'layout-sidebar-left-expand',
	'menu-2',
	'mood-sad',
	'moon',
	'pencil',
	'plus',
	'sparkles',
	'sun',
	'x'
];

const require = createRequire(import.meta.url);
const set = require('@iconify-json/tabler/icons.json');
const info = require('@iconify-json/tabler/info.json');

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());

const exports = NAMES.map((name) => {
	const icon = set.icons[name];
	if (!icon) throw new Error(`Tabler has no icon named "${name}"`);
	const data = {
		body: icon.body,
		width: icon.width ?? set.width,
		height: icon.height ?? set.height
	};
	return `export const ${camel(name)}: IconifyIcon = ${JSON.stringify(data)};`;
});

writeFileSync(
	'src/lib/icons.ts',
	[
		`// Generated by scripts/icons.js from ${info.name} (${info.license.spdx}, ${info.author.url}).`,
		`import type { IconifyIcon } from '@iconify/svelte';`,
		'',
		...exports,
		''
	].join('\n')
);
console.log(`icons: ${NAMES.length} icons written to src/lib/icons.ts`);
