// Writes src/lib/icons.ts: the icons the components show, as data for `@iconify/svelte`,
// so they render at once, offline too, without asking the Iconify API. To add one, put its
// Tabler name in NAMES, or a brand logo's Simple Icons name in BRANDS, and run `npm run icons`.

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const NAMES = [
	'brand-github-filled',
	'brand-linkedin-filled',
	'check',
	'chevron-left',
	'chevron-right',
	'copy',
	'device-desktop',
	'file-text',
	'folder',
	'folder-open',
	'git-pull-request',
	'hash',
	'layout-sidebar-left-collapse',
	'layout-sidebar-left-expand',
	'mail',
	'menu-2',
	'mood-sad',
	'moon',
	'pencil',
	'plus',
	'search',
	'sparkles',
	'sun',
	'x'
];

const BRANDS = ['helm'];

const require = createRequire(import.meta.url);
const sources = [
	{
		prefix: '',
		names: NAMES,
		set: require('@iconify-json/tabler/icons.json'),
		info: require('@iconify-json/tabler/info.json')
	},
	{
		prefix: 'brand-',
		names: BRANDS,
		set: require('@iconify-json/simple-icons/icons.json'),
		info: require('@iconify-json/simple-icons/info.json')
	}
];

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());

const exports = sources.flatMap(({ prefix, names, set, info }) =>
	names.map((name) => {
		const icon = set.icons[name];
		if (!icon) throw new Error(`${info.name} has no icon named "${name}"`);
		const data = {
			body: icon.body,
			width: icon.width ?? set.width,
			height: icon.height ?? set.height
		};
		return `export const ${camel(prefix + name)}: IconifyIcon = ${JSON.stringify(data)};`;
	})
);

writeFileSync(
	'src/lib/icons.ts',
	[
		...sources.map(
			({ info }) =>
				`// Generated by scripts/icons.js from ${info.name} (${info.license.spdx}, ${info.author.url}).`
		),
		`import type { IconifyIcon } from '@iconify/svelte';`,
		'',
		...exports,
		''
	].join('\n')
);
console.log(`icons: ${exports.length} icons written to src/lib/icons.ts`);
